def check_complete_set(yes_atoms, no_atoms):
    """One-share Yes plus No from the uniform start lies between the paper's price sums before and after."""
    with localcontext() as context:
        context.prec = 80
        k = D(rate(2, 500)) / WAD
        start = instant_prices(2, 10, k, [0, 0, 0, 0])
        assert abs(sum(start) - (1 + D('0.05'))) < D('1e-15')
        yes_before = start[1] + start[3]
        no_before = start[0] + start[2]
        yes_after = instant_prices(2, 10 + k / 2, k, liabilities(2, [(1, [0, 1])]))
        no_after = instant_prices(2, 10 + k / 2, k, liabilities(2, [(1, [1, 0])]))
        upper = yes_after[1] + yes_after[3] + no_after[0] + no_after[2]
        total = D(yes_atoms + no_atoms) / 10**6
        assert 1 < yes_before + no_before <= total <= upper + D('2e-6'), (total, yes_before + no_before, upper)


def sig30(calculate):
    def at(precision):
        with localcontext() as context:
            context.prec = precision
            return f'{calculate():.30g}'
    result = at(80)
    assert result == at(120)
    return result


def rust_rows():
    header = 'name,events,initial_depth,commission_bps,step,scope,mask,quantity,cost_delta,depth_after'
    sequences = [
        ('uniform_yes', 2, 10, 500, [([0], 2, 1)]),
        ('uniform_and', 2, 10, 500, [([0, 1], 8, 1)]),
        ('balanced', 2, 10, 500, [([0], 2, 10), ([0], 1, 10)]),
        ('informed', 2, 10, 500, [([0], 2, 10)] * 4),
    ]
    for bps in [100, 500, 2000]:
        sequences.append((f'three_event_{bps}', 3, 100, bps,
                          [([0], 2, 20), ([1, 2], 8, 15), ([0, 2], 5, 12), ([0, 1, 2], 85, 9), ([1, 2], 8, -5)]))
    rows = [header]
    for name, events, initial, bps, trades in sequences:
        factors = []
        for step, (scope, mask, quantity) in enumerate(trades):
            mask_scope = sum(1 << e for e in scope)
            after = apply(factors, mask_scope, mask, quantity)

            def real_depth(fs):
                k = D(bps) / 10000 / (events * D(2).ln())
                mean = sum(D(sum(v)) / (1 << size(s)) for s, v in fs)
                return D(initial) + k * mean

            def delta(before=factors, after=after):
                db, da = real_depth(before), real_depth(after)
                ours = g_cost(da, liabilities(events, after)) - g_cost(db, liabilities(events, before))
                k = D(bps) / 10000 / (events * D(2).ln())
                paper = paper_cost(events, D(initial), k, liabilities(events, after)) - paper_cost(events, D(initial), k, liabilities(events, before))
                assert abs(paper - ours) < D('1e-30')
                return ours

            cost = sig30(delta)
            depth_after = sig30(lambda after=after: real_depth(after))
            rows.append(f'{name},{events},{initial},{bps},{step},{";".join(map(str, scope))},{mask},{quantity},{cost},{depth_after}')
            factors = after
    return '\n'.join(rows) + '\n', len(rows) - 1


def web():
    rates = [dict(events=n, commissionBps=bps, rateWad=str(rate(n, bps)))
             for n, bps in [(2, 500), (3, 1000), (32, 500), (2, 100), (2, 2000), (4, 500)]]
    chain = [(3, [5_000_000, 0, 3_000_000, 7_000_000]), (6, [5_000_000, 0, 3_000_000, 7_000_000]),
             (12, [5_000_000, 0, 3_000_000, 7_000_000])]
    depth_cases = [(2, []), (2, [(1, [0, 1_000_000])]), (2, [(3, [0, 0, 0, 10_000_000])]), (4, chain)]
    depths = []
    for events, factors in depth_cases:
        value = depth(10_000_000 * ATOM_TO_WAD, rate(events, 500), scaled(factors, ATOM_TO_WAD))
        depths.append(dict(events=events, commissionBps=500, initialDepthAtoms='10000000',
                           factors=[dict(scope=s, values=list(map(str, v))) for s, v in factors], depthWad=str(value)))
    probability_cases = [('ls-uniform-two', 2, [], 0, 1), ('ls-yes-ten', 2, [(1, [0, 10_000_000])], 0, 1),
                         ('ls-positive-relationship', 2, [(3, [0, 0, 0, 10_000_000])], 0, 1),
                         ('ls-chain-four', 4, chain, 0, 3), ('ls-rare', 4, [(2, [1_000_000_000, 0])], 0, 1)]
    probabilities = []
    for name, events, factors, a, b in probability_cases:
        wad = scaled(factors, ATOM_TO_WAD)
        value = depth(10_000_000 * ATOM_TO_WAD, rate(events, 500), wad)
        row = pair_fixture(name, events, wad, liquidity=value, a=a, b=b)
        row['input'] = dict(events=events, a=a, b=b, initialDepthAtoms='10000000', commissionBps=500,
                            order=list(range(events)), factors=[dict(scope=s, values=list(map(str, v))) for s, v in factors])
        probabilities.append(row)
    data = dict(rates=rates, depths=depths, probabilities=probabilities)
    return json.dumps(data, indent=2) + '\n', len(rates) + len(depths) + len(probabilities)


