WAD = 10**18
LN2_WAD = 693147180559945309
MIN_BPS, MAX_BPS = 100, 2000
ATOM_TO_WAD = 10**12


def rate(events, bps):
    assert 0 < events <= 32 and MIN_BPS <= bps <= MAX_BPS
    return bps * 10**14 * WAD // (events * LN2_WAD)


def size(scope):
    return bin(scope).count('1')


def depth(initial_wad, r, factors_wad):
    total = 0
    for scope, values in factors_wad:
        assert size(scope) <= 3 and len(values) == 1 << size(scope)
        total += sum(values) * (8 >> size(scope))
    return initial_wad + r * total // (8 * WAD)


def local(state, scope, events):
    bits = [event for event in range(events) if scope & (1 << event)]
    return sum(((state >> event) & 1) << bit for bit, event in enumerate(bits))


def liabilities(events, factors):
    return [sum(values[local(x, scope, events)] for scope, values in factors) for x in range(2**events)]


def g_cost(b, q):
    b = D(b)
    return b * sum((D(v) / b).exp() for v in q).ln()


def paper_cost(events, initial, r, q):
    seed = D(initial) / D(r)
    shares = [seed + D(v) for v in q]
    b = D(r) / D(2**events) * sum(shares)
    return b * sum((v / b).exp() for v in shares).ln()


def instant_prices(events, b, k, q):
    """Paper Sec. 3.3.1 over joint states: p(x) = w(x) + alpha H(w), alpha = k / 2^events."""
    b = D(b)
    weights = [(D(v) / b).exp() for v in q]
    total = sum(weights)
    w = [x / total for x in weights]
    entropy = -sum(x * x.ln() for x in w if x > 0)
    return [x + D(k) / D(2**events) * entropy for x in w]


def apply(factors, scope, mask, quantity):
    merged = [0] * (1 << size(scope))
    rest = []
    for s, values in factors:
        if s == scope:
            merged = [a + b for a, b in zip(merged, values)]
        else:
            rest.append((s, list(values)))
    for j in range(len(merged)):
        if mask & (1 << j):
            merged[j] += quantity
            assert merged[j] >= 0
    return rest + [(scope, merged)]


def scaled(factors, factor):
    return [(s, [v * factor for v in values]) for s, values in factors]


def check_paper(events, initial_wad, r, before, after, scale):
    """Quotes equal the paper's cost differences up to the floor on depth (Appendix A.6)."""
    with localcontext() as context:
        context.prec = 80
        lb, la = liabilities(events, scaled(before, scale)), liabilities(events, scaled(after, scale))
        initial, rr = D(initial_wad) / WAD, D(r) / WAD
        paper = paper_cost(events, initial, rr, [D(v) / WAD for v in la]) - paper_cost(events, initial, rr, [D(v) / WAD for v in lb])
        db = D(depth(initial_wad, r, scaled(before, scale))) / WAD
        da = D(depth(initial_wad, r, scaled(after, scale))) / WAD
        ours = g_cost(da, [D(v) / WAD for v in la]) - g_cost(db, [D(v) / WAD for v in lb])
        assert abs(paper - ours) < D('1e-12'), (paper, ours)


def ideal_atoms(events, initial_wad, r, before, after, scale, is_buy):
    lb, la = liabilities(events, scaled(before, scale)), liabilities(events, scaled(after, scale))
    db, da = depth(initial_wad, r, scaled(before, scale)), depth(initial_wad, r, scaled(after, scale))
    floor, ceil = stable(lambda: (g_cost(da, la) - g_cost(db, lb)) / scale * (1 if is_buy else -1))
    ideal = ceil if is_buy else floor
    assert ideal > 0
    return ideal, da


